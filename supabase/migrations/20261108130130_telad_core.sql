-- Telad: listings (seller-typed numbers), private seller data, buyer requests, admins.
-- Applied to Supabase project xvxwvkxashwizafetltl as migration "telad_core".
create table public.listings (
  id bigint generated by default as identity (start with 101) primary key,
  code text unique,
  state text not null default 'pending' check (state in ('pending','approved','rejected','sold','hidden')),
  zone text not null check (zone in ('القادسية','الأمل')),
  district smallint not null,
  neighborhood smallint check (neighborhood between 1 and 10),
  block text check (char_length(block) <= 40),
  area_orig numeric(8,2) not null check (area_orig > 0 and area_orig < 100000),
  area_final numeric(8,2) not null check (area_final > 0 and area_final < 100000),
  facade text check (facade in ('بحري','قبلي','شرقي','غربي','ناصية')),
  view_type text check (view_type in ('شارع رئيسي','حديقة','خدمات','داخلي')),
  price numeric(14,1) not null check (price > 0),
  paid numeric(14,1) not null check (paid >= 0),
  over_amount numeric(14,1) not null check (over_amount >= 0),
  remaining numeric(14,1) generated always as (price - paid) stored,
  inst_left smallint not null check (inst_left between 1 and 3),
  description text not null default '' check (char_length(description) <= 1000),
  created_at timestamptz not null default now(),
  reviewed_at timestamptz,
  published_at timestamptz,
  check (paid <= price),
  check ((zone = 'القادسية' and district in (8,9,10,12,17,20,21,22,23)) or (zone = 'الأمل' and district in (28,29,30,32,33,34,35,36)))
);
create index listings_state_idx on public.listings (state, published_at desc);

create table public.listing_private (
  listing_id bigint primary key references public.listings(id) on delete cascade,
  owner_name text not null check (char_length(btrim(owner_name)) between 2 and 80),
  phone text not null check (phone ~ '^01[0125][0-9]{8}$'),
  plot_number text check (char_length(plot_number) <= 40)
);

create table public.requests (
  id bigint generated always as identity primary key,
  kind text not null check (kind in ('unit','ask')),
  listing_id bigint references public.listings(id) on delete set null,
  name text not null check (char_length(btrim(name)) between 2 and 80),
  phone text not null check (phone ~ '^01[0125][0-9]{8}$'),
  zone text check (zone in ('القادسية','الأمل')),
  district smallint,
  budget numeric(14,1) check (budget >= 0),
  state text not null default 'new' check (state in ('new','contacted','closed')),
  created_at timestamptz not null default now()
);
create index requests_state_idx on public.requests (state, created_at desc);
create index requests_listing_idx on public.requests (listing_id);

create table public.admins (
  user_id uuid primary key references auth.users(id) on delete cascade,
  created_at timestamptz not null default now()
);

alter table public.listings enable row level security;
alter table public.listing_private enable row level security;
alter table public.requests enable row level security;
alter table public.admins enable row level security;

revoke all on public.listings, public.listing_private, public.requests, public.admins from anon, authenticated;
grant select on public.listings to anon, authenticated;
create policy "published listings are public" on public.listings for select to anon, authenticated using (state = 'approved');

-- ---------- helpers ----------
create or replace function public.is_admin() returns boolean
language sql stable security definer set search_path = ''
as $$ select exists (select 1 from public.admins a where a.user_id = (select auth.uid())); $$;

-- ---------- public actions ----------
create or replace function public.submit_offer(p jsonb) returns bigint
language plpgsql security definer set search_path = ''
as $$
declare v_id bigint; v_phone text := p->>'phone';
begin
  if coalesce(v_phone,'') !~ '^01[0125][0-9]{8}$' then raise exception 'invalid_phone' using errcode = '22023'; end if;
  if char_length(btrim(coalesce(p->>'name',''))) not between 2 and 80 then raise exception 'invalid_name' using errcode = '22023'; end if;
  if (select count(*) from public.listing_private pr join public.listings l on l.id = pr.listing_id
      where pr.phone = v_phone and l.created_at > now() - interval '1 day') >= 5 then
    raise exception 'too_many_offers' using errcode = '22023'; end if;
  if (select count(*) from public.listings where created_at > now() - interval '1 hour') >= 60 then
    raise exception 'busy' using errcode = '22023'; end if;
  insert into public.listings (zone, district, neighborhood, block, area_orig, area_final, facade, view_type, price, paid, over_amount, inst_left, description)
  values (p->>'zone', (p->>'district')::smallint, nullif(p->>'neighborhood','')::smallint, nullif(btrim(coalesce(p->>'block','')),''),
    (p->>'area_orig')::numeric, (p->>'area_final')::numeric, nullif(p->>'facade',''), nullif(p->>'view_type',''),
    round((p->>'price')::numeric, 1), round((p->>'paid')::numeric, 1), round((p->>'over_amount')::numeric, 1), (p->>'inst_left')::smallint,
    btrim(coalesce(p->>'description','')))
  returning id into v_id;
  insert into public.listing_private (listing_id, owner_name, phone, plot_number)
  values (v_id, btrim(p->>'name'), v_phone, nullif(btrim(coalesce(p->>'plot_number','')),''));
  return v_id;
end $$;

create or replace function public.submit_request(p jsonb) returns void
language plpgsql security definer set search_path = ''
as $$
declare v_phone text := p->>'phone'; v_listing bigint := nullif(p->>'listing_id','')::bigint;
begin
  if coalesce(v_phone,'') !~ '^01[0125][0-9]{8}$' then raise exception 'invalid_phone' using errcode = '22023'; end if;
  if char_length(btrim(coalesce(p->>'name',''))) not between 2 and 80 then raise exception 'invalid_name' using errcode = '22023'; end if;
  if v_listing is not null and not exists (select 1 from public.listings where id = v_listing and state = 'approved') then
    raise exception 'listing_not_found' using errcode = '22023'; end if;
  if (select count(*) from public.requests where phone = v_phone and created_at > now() - interval '1 day') >= 20 then
    raise exception 'too_many_requests' using errcode = '22023'; end if;
  insert into public.requests (kind, listing_id, name, phone, zone, district, budget)
  values (case when v_listing is null then 'ask' else 'unit' end, v_listing, btrim(p->>'name'), v_phone,
    nullif(p->>'zone',''), nullif(p->>'district','')::smallint, nullif(p->>'budget','')::numeric);
end $$;

-- ---------- admin ----------
create or replace function public.admin_listings() returns setof jsonb
language plpgsql stable security definer set search_path = ''
as $$
begin
  if not public.is_admin() then raise exception 'not_admin' using errcode = '42501'; end if;
  return query select to_jsonb(l) || jsonb_build_object('owner_name', pr.owner_name, 'phone', pr.phone, 'plot_number', pr.plot_number,
      'request_count', (select count(*) from public.requests r where r.listing_id = l.id))
    from public.listings l left join public.listing_private pr on pr.listing_id = l.id order by l.created_at desc;
end $$;

create or replace function public.admin_set_state(p_id bigint, p_state text) returns text
language plpgsql security definer set search_path = ''
as $$
declare v_code text;
begin
  if not public.is_admin() then raise exception 'not_admin' using errcode = '42501'; end if;
  if p_state not in ('pending','approved','rejected','sold','hidden') then raise exception 'invalid_state' using errcode = '22023'; end if;
  update public.listings set state = p_state, reviewed_at = now(),
    published_at = case when p_state = 'approved' then coalesce(published_at, now()) else published_at end,
    code = case when p_state = 'approved' and code is null
      then (case zone when 'القادسية' then 'Q' else 'A' end) || to_char(now() at time zone 'Africa/Cairo', 'YYMM') || '-' || id
      else code end
  where id = p_id returning code into v_code;
  if not found then raise exception 'listing_not_found' using errcode = '22023'; end if;
  return v_code;
end $$;

create or replace function public.admin_requests() returns setof jsonb
language plpgsql stable security definer set search_path = ''
as $$
begin
  if not public.is_admin() then raise exception 'not_admin' using errcode = '42501'; end if;
  return query select to_jsonb(r) || jsonb_build_object('code', l.code, 'l_district', l.district, 'l_area', l.area_final, 'l_price', l.price,
      'owner_name', pr.owner_name, 'owner_phone', pr.phone)
    from public.requests r left join public.listings l on l.id = r.listing_id left join public.listing_private pr on pr.listing_id = l.id
    order by (r.state = 'new') desc, r.created_at desc;
end $$;

create or replace function public.admin_set_request_state(p_id bigint, p_state text) returns void
language plpgsql security definer set search_path = ''
as $$
begin
  if not public.is_admin() then raise exception 'not_admin' using errcode = '42501'; end if;
  if p_state not in ('new','contacted','closed') then raise exception 'invalid_state' using errcode = '22023'; end if;
  update public.requests set state = p_state where id = p_id;
end $$;

revoke execute on function public.is_admin(), public.submit_offer(jsonb), public.submit_request(jsonb), public.admin_listings(),
  public.admin_set_state(bigint,text), public.admin_requests(), public.admin_set_request_state(bigint,text) from public, anon, authenticated;
grant execute on function public.submit_offer(jsonb), public.submit_request(jsonb) to anon, authenticated;
grant execute on function public.is_admin(), public.admin_listings(), public.admin_set_state(bigint,text), public.admin_requests(),
  public.admin_set_request_state(bigint,text) to authenticated;
