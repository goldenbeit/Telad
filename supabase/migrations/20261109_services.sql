-- Telad solutions: requests for investment, development, partnership, asset management, valuation, consultation.
create table public.service_requests (
  id bigint generated by default as identity (start with 1001) primary key,
  service text not null check (service in ('invest','develop','partner','assets','valuation','consult')),
  answers jsonb not null default '{}'::jsonb check (jsonb_typeof(answers) = 'object' and pg_column_size(answers) < 4000),
  name text not null check (char_length(btrim(name)) between 2 and 80),
  phone text not null check (phone ~ '^01[0125][0-9]{8}$'),
  channel text not null default 'واتساب' check (channel in ('واتساب','مكالمة هاتفية')),
  contact_time text check (contact_time in ('صباحاً','مساءً','أي وقت')),
  state text not null default 'new' check (state in ('new','contacted','closed')),
  created_at timestamptz not null default now()
);
create index service_requests_state_idx on public.service_requests (state, created_at desc);
alter table public.service_requests enable row level security;
revoke all on public.service_requests from anon, authenticated;

create or replace function public.submit_service_request(p jsonb) returns bigint
language plpgsql security definer set search_path = ''
as $$
declare v_id bigint; v_phone text := p->>'phone';
begin
  if coalesce(v_phone,'') !~ '^01[0125][0-9]{8}$' then raise exception 'invalid_phone' using errcode = '22023'; end if;
  if char_length(btrim(coalesce(p->>'name',''))) not between 2 and 80 then raise exception 'invalid_name' using errcode = '22023'; end if;
  if (select count(*) from public.service_requests where phone = v_phone and created_at > now() - interval '1 day') >= 10 then
    raise exception 'too_many_requests' using errcode = '22023'; end if;
  if (select count(*) from public.service_requests where created_at > now() - interval '1 hour') >= 100 then
    raise exception 'busy' using errcode = '22023'; end if;
  insert into public.service_requests (service, answers, name, phone, channel, contact_time)
  values (p->>'service', coalesce(p->'answers', '{}'::jsonb), btrim(p->>'name'), v_phone,
    coalesce(nullif(p->>'channel',''), 'واتساب'), nullif(p->>'contact_time',''))
  returning id into v_id;
  return v_id;
end $$;

create or replace function public.admin_service_requests() returns setof jsonb
language plpgsql stable security definer set search_path = ''
as $$
begin
  if not public.is_admin() then raise exception 'not_admin' using errcode = '42501'; end if;
  return query select to_jsonb(s) from public.service_requests s order by (s.state = 'new') desc, s.created_at desc;
end $$;

create or replace function public.admin_set_service_request_state(p_id bigint, p_state text) returns void
language plpgsql security definer set search_path = ''
as $$
begin
  if not public.is_admin() then raise exception 'not_admin' using errcode = '42501'; end if;
  if p_state not in ('new','contacted','closed') then raise exception 'invalid_state' using errcode = '22023'; end if;
  update public.service_requests set state = p_state where id = p_id;
end $$;

revoke execute on function public.submit_service_request(jsonb), public.admin_service_requests(), public.admin_set_service_request_state(bigint,text) from public, anon, authenticated;
grant execute on function public.submit_service_request(jsonb) to anon, authenticated;
grant execute on function public.admin_service_requests(), public.admin_set_service_request_state(bigint,text) to authenticated;
